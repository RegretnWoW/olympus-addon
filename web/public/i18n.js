// Olympus Link: the page's words. English by default, Brazilian Portuguese when the browser's
// language starts with "pt" (or ?lang=pt). {name} marks a value the page fills in ({command}: the
// bot's command, CONFIG.VERIFY_COMMAND). Every reason the bot's POST /proof answers has its words in
// `errors` (web/worker/link-core.mjs, PROOF_REASONS; web/test/page.test.mjs checks it).

export function pickLang(param, navigatorLanguage) {
	if (param === 'en' || param === 'pt') return param;
	return String(navigatorLanguage || '').toLowerCase().startsWith('pt') ? 'pt' : 'en';
}

export function fill(text, vars = {}) {
	return String(text).replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

